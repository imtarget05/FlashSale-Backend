using System.Net.Http.Json;
using System.Text.Json;
using OpsBridge.Application.Connectors;
using OpsBridge.Domain.Contracts;
using OpsBridge.Infrastructure.Security;

namespace OpsBridge.Infrastructure.Connectors;

public sealed class MockFactoryFlowClient(HttpClient httpClient) : IFactoryFlowClient
{
    private static readonly JsonSerializerOptions JsonOpts = new()
    {
        PropertyNamingPolicy = JsonNamingPolicy.CamelCase,
        WriteIndented = false
    };

    public Task<bool> PingAsync(CancellationToken ct = default)
    {
        return Task.FromResult(true);
    }

    public Task<GoodsReceiptConfirmedV1?> GetGoodsReceiptAsync(string receiptNumber, CancellationToken ct = default)
    {
        // Deterministic contract mock for development
        var mock = new GoodsReceiptConfirmedV1(
            Guid.NewGuid(),
            GoodsReceiptConfirmedV1.ExpectedEventType,
            GoodsReceiptConfirmedV1.ExpectedSchemaVersion,
            GoodsReceiptConfirmedV1.ExpectedSource,
            DateTimeOffset.UtcNow,
            Guid.NewGuid(),
            new GoodsReceiptDataV1(
                Guid.NewGuid(),
                receiptNumber,
                "PO-2026-0891",
                "SUP-ACME-01",
                DateTimeOffset.UtcNow.AddMinutes(-30),
                "WH-MAIN-01",
                "mock_warehouse_worker",
                "Generated by MockFactoryFlowClient",
                [
                    new GoodsReceiptItemV1(
                        "RM-ALUM-SHEET-02",
                        "Aluminum Sheet 2mm Standard",
                        1,
                        150.0m,
                        0.0m,
                        "KG",
                        "LOT-MOCK-2026",
                        "Accepted"
                    )
                ]
            )
        );

        return Task.FromResult<GoodsReceiptConfirmedV1?>(mock);
    }

    public async Task<WebhookDeliveryResult> SendGoodsReceiptWebhookAsync(
        string targetWebhookUrl,
        GoodsReceiptConfirmedV1 payload,
        string secret,
        CancellationToken ct = default)
    {
        var rawJson = JsonSerializer.Serialize(payload, JsonOpts);
        var timestamp = DateTimeOffset.UtcNow.ToUnixTimeSeconds().ToString();
        var signature = HmacWebhookVerifier.ComputeSignatureHeader(rawJson, timestamp, secret, "v1=");

        var request = new HttpRequestMessage(HttpMethod.Post, targetWebhookUrl)
        {
            Content = new StringContent(rawJson, System.Text.Encoding.UTF8, "application/json")
        };

        request.Headers.Add("svix-id", payload.EventId.ToString());
        request.Headers.Add("svix-timestamp", timestamp);
        request.Headers.Add("svix-signature", signature);

        var response = await httpClient.SendAsync(request, ct);
        var responseBody = await response.Content.ReadAsStringAsync(ct);

        return new WebhookDeliveryResult(
            response.IsSuccessStatusCode,
            (int)response.StatusCode,
            responseBody
        );
    }
}
